_TEMP = []


def tree(files):
    """Write {path under src/: text} to a temporary checkout and return it."""
    temp = tempfile.TemporaryDirectory()
    _TEMP.append(temp)
    root = Path(temp.name)
    for rel, text in files.items():
        path = root / "src" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(textwrap.dedent(text), encoding="utf-8")
    return root


def values(files):
    return health.measure_source(tree(files))[0]


def run_in(cwd, argv, github_actions=False):
    env = {k: v for k, v in os.environ.items() if k != "GITHUB_ACTIONS"}
    if github_actions:
        env["GITHUB_ACTIONS"] = "true"
    out, old = io.StringIO(), os.getcwd()
    os.chdir(cwd)
    try:
        with mock.patch.dict(os.environ, env, clear=True), contextlib.redirect_stdout(out):
            code = health.main(argv)
    finally:
        os.chdir(old)
    return code, out.getvalue()


def tearDownModule():
    for temp in _TEMP:
        temp.cleanup()


def body(n):
    return "fn long() {\n" + "    let x = 1;\n" * (n - 2) + "}\n"


class Functions(unittest.TestCase):
    def test_counts_signature_to_closing_brace(self):
        found = list(health.functions("fn a(x: Vec<u8>) -> u8\nwhere u8: Copy\n{\n    1\n}\n"))
        self.assertEqual(found, [("a", 1, 5)])

    def test_array_return_type_is_not_a_declaration(self):
        found = list(health.functions("fn a(w: [bool; 3]) -> [Vec<String>; 3] {\n    x\n}\n"))
        self.assertEqual(found, [("a", 1, 3)])

    def test_declaration_without_body_is_skipped(self):
        self.assertEqual(list(health.functions("trait T { fn a(&self); fn b() {} }")), [("b", 1, 1)])

    def test_long_function_threshold(self):
        self.assertEqual(values({"io/a.rs": body(150)})["long_functions"], 0)
        self.assertEqual(values({"io/a.rs": body(151)})["long_functions"], 1)

    def test_generated_files_are_left_out_of_the_size_measures(self):
        gen = "//! Generated lookup table.\n" + body(200) + "\n" * 3000 + "fn g() { a.unwrap(); }\n"
        root = tree({"locale.rs": gen, "io/a.rs": "fn f() {}\n"})
        v, d = health.measure_source(root)
        self.assertEqual((v["long_functions"], v["large_files"], v["panic_sites"]), (0, 0, 1))
        self.assertEqual(d["generated_files"], ["src/locale.rs"])
        self.assertTrue(health.generated("// @generated by build.rs\nfn a() {}\n"))
        self.assertFalse(health.generated("fn a() {}\n" * 6 + "// Generated below\n"))

    def test_test_code_is_not_counted(self):
        self.assertEqual(values({"io/a.rs": "#[cfg(test)]\nmod tests {\n" + body(200) + "}\n"})["long_functions"], 0)


class Panics(unittest.TestCase):
    def test_counts_unwrap_expect_panic_in_production_code(self):
        v = values({"io/a.rs": 'fn f() { a.unwrap(); b.expect("x"); panic!("y"); c.unwrap_or(1); }\n'})
