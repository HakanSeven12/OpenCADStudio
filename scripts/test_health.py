class Diff(unittest.TestCase):
    base = {"io/a.rs": "fn f() {\n    a.unwrap();\n}\n", "entities/a.rs": "use crate::scene::S;\n"}

    def test_improvements_are_thanked_and_regressions_located(self):
        head = {"io/a.rs": "fn f() {\n    a.unwrap();\n    b.unwrap();\n}\n", "entities/a.rs": "\n"}
        code, out = run_in(tree(head), ["diff", str(tree(self.base)), "--markdown"])
        self.assertEqual(code, 0)
        self.assertIn("Thank you: this pull request improves", out)
        self.assertIn("upward dependencies (files): 1 → 0", out)
        self.assertIn("unwrap/expect/panic! in production code: 1 → 2", out)
        self.assertIn("`src/io/a.rs:3`", out)
        self.assertIn("Upward dependencies removed (1)", out)

    def test_a_missing_message_enum_is_not_a_change(self):
        _, out = run_in(tree({"app/mod.rs": "pub enum Message {\n    A,\n}\n"}), ["diff", str(tree({"io/a.rs": "\n"})), "--markdown"])
        self.assertNotIn("Message variants", out)

    def test_moved_lines_are_not_new(self):
        head = {"io/a.rs": "\n\nfn f() {\n    a.unwrap();\n}\n", "entities/a.rs": "use crate::scene::S;\n"}
        code, out = run_in(tree(head), ["diff", str(tree(self.base)), "--markdown"])
        self.assertIn("No change to the source measures.", out)
        self.assertNotIn("New unwrap", out)

    def test_existing_large_files_and_mutual_pairs_are_not_new(self):
        base = {"io/a.rs": "use crate::scene::S;\n" + "\n" * 3001, "scene/a.rs": "use crate::io::L;\n"}
        head = {"io/a.rs": "use crate::scene::S;\n" + "\n" * 3100, "scene/a.rs": "use crate::io::L;\n",
                "io/b.rs": "\n" * 3001}
        _, out = run_in(tree(head), ["diff", str(tree(base)), "--markdown"])
        self.assertIn("Files now over 3,000 lines (1)", out)
        self.assertIn("`src/io/b.rs`", out)
        self.assertNotIn("`src/io/a.rs` (", out)
        self.assertNotIn("Modules that now use each other", out)

    def test_a_long_function_that_grows_is_not_new(self):
        base = {"io/a.rs": body(200)}
        head = {"io/a.rs": body(220), "io/b.rs": body(160).replace("fn long", "fn other")}
        _, out = run_in(tree(head), ["diff", str(tree(base)), "--markdown"])
        self.assertIn("Functions now over 150 lines (1)", out)
        self.assertIn("`other`", out)

    def test_annotations_in_github_actions(self):
        head = dict(self.base, **{"io/b.rs": "fn g() { c.expect(\"x\"); }\n"})
        _, out = run_in(tree(head), ["diff", str(tree(self.base))], github_actions=True)
        self.assertIn("::warning file=src/io/b.rs,line=1,title=New panic site::", out)


def clippy_line(file, line, code, fixable=False, children=False):
    span = {"file_name": file, "line_start": line, "is_primary": True,
            "suggestion_applicability": "MachineApplicable" if fixable and not children else None}
    msg = {"level": "warning", "message": f"{code} here", "code": {"code": code} if code else None, "spans": [span],
           "children": [{"spans": [dict(span, suggestion_applicability="MachineApplicable")]}] if children else []}
    return json.dumps({"reason": "compiler-message", "message": msg})


class Lint(unittest.TestCase):
    def test_parse_clippy_dedupes_and_splits_rustc(self):
        lines = [clippy_line("src/a.rs", 1, "clippy::len_zero", fixable=True),
                 clippy_line("src/a.rs", 1, "clippy::len_zero", fixable=True),
                 clippy_line("src/a.rs", 2, "clippy::too_many_arguments"),
                 clippy_line("src/b.rs", 3, "dead_code", children=True),
                 json.dumps({"reason": "build-finished"}), "not json"]
        clippy, rustc = health.parse_clippy(lines)
        self.assertEqual([(w["code"], w["fixable"]) for w in clippy],
                         [("clippy::len_zero", True), ("clippy::too_many_arguments", False)])
        self.assertEqual([(w["code"], w["fixable"]) for w in rustc], [("dead_code", True)])

    def test_lint_reports_only_touched_files(self):
        d = Path(tempfile.mkdtemp())
        (d / "c.json").write_text("\n".join([clippy_line("src/a.rs", 1, "clippy::len_zero", fixable=True),
                                             clippy_line("src/b.rs", 2, "clippy::len_zero")]))
        (d / "fmt.txt").write_text("/home/runner/work/x/src/b.rs\n/home/runner/work/x/src/a.rs\n")
        (d / "changed.txt").write_text("src/a.rs\nREADME.md\n")
        _, out = run_in(d, ["lint", str(d / "c.json"), str(d / "fmt.txt"), str(d / "changed.txt"), "--markdown"])
        self.assertIn("1 warning(s) in 1 file(s); 1 can be fixed automatically", out)
        self.assertIn("rustfmt would change 1 touched file(s)", out)

    def test_clean_touched_files_are_thanked(self):
        d = Path(tempfile.mkdtemp())
        (d / "c.json").write_text(clippy_line("src/b.rs", 2, "clippy::len_zero"))
        (d / "fmt.txt").write_text("")
        (d / "changed.txt").write_text("src/a.rs\n")
        _, out = run_in(d, ["lint", str(d / "c.json"), str(d / "fmt.txt"), str(d / "changed.txt"), "--markdown"])
        self.assertIn("None. Thank you", out)


def git_repo():
    """A repository with: a base commit; a pull request (author Alice) that
    removes an upward dependency, merged by Merger as `Merge #7: ...`; a
    pull request (author Bob) that removes a panic site, merged as
    `Merge branch 'pr9'`; then a direct commit that adds a panic site."""
    temp = tempfile.TemporaryDirectory()
    _TEMP.append(temp)
    root = Path(temp.name)

    def git(*args, author="Merger"):
        env = {**os.environ, "GIT_AUTHOR_NAME": author, "GIT_AUTHOR_EMAIL": "a@example.com",
               "GIT_COMMITTER_NAME": author, "GIT_COMMITTER_EMAIL": "a@example.com"}
        env.pop("GH_TOKEN", None)
        subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, env=env)

    def write(rel, text):
        path = root / "src" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    git("init", "-q", "-b", "main")
    write("entities/a.rs", "use crate::scene::S;\n")
    write("io/a.rs", "fn f() {}\n")
    write("scene/a.rs", "fn g() { x.unwrap(); }\n")
    git("add", "-A")
    git("commit", "-q", "-m", "Base")
    git("checkout", "-q", "-b", "fix")
    write("entities/a.rs", "\n")
    git("commit", "-q", "-am", "Remove the upward use", author="Alice")
    git("checkout", "-q", "main")
    git("merge", "-q", "--no-ff", "fix", "-m", "Merge #7: Remove the upward use")
    git("checkout", "-q", "-b", "pr9")
    write("scene/a.rs", "fn g() {}\n")
    git("commit", "-q", "-am", "Return instead of unwrapping", author="Bob")
    git("checkout", "-q", "main")
    git("merge", "-q", "--no-ff", "pr9", "-m", "Merge branch 'pr9'")
    write("io/a.rs", "fn f() { a.unwrap(); }\n")
    git("commit", "-q", "-am", "Add a panic site (#8)")
    return root


class Credits(unittest.TestCase):
    def test_credits_the_pull_request_author_and_skips_regressions(self):
        root = git_repo()
        with mock.patch.dict(os.environ, {k: v for k, v in os.environ.items() if k != "GH_TOKEN"}, clear=True):
            found = health.credits("main~3", "main", root)
        self.assertEqual([(c["pr"], c["login"], c["author"]) for c in found], [(7, None, "Alice"), (9, None, "Bob")])
        self.assertEqual(found[0]["improved"], {"upward_pairs": [1, 0], "upward_files": [1, 0]})
        self.assertEqual(found[1]["improved"], {"panic_sites": [1, 0]})


